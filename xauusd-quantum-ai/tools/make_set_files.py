#!/usr/bin/env python3
"""Generate MT5 preset files (.set) from the EA input defaults + per-mode overrides.

    python tools/make_set_files.py

Reads mql5/Experts/XauQuantumAI/XauQuantumAI.mq5 so presets never drift from the code.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "mql5/Experts/XauQuantumAI/XauQuantumAI.mq5"
ENUMS = {"XQ_MODE_BACKTEST": 0, "XQ_MODE_DEMO": 1, "XQ_MODE_LIVE": 2, "XQ_AI_OFF": 0, "XQ_AI_NATIVE": 1,
         "XQ_AI_BRIDGE": 2, "XQ_AI_BRIDGE_FALLBACK": 3, "XQ_DEGRADED_NO_TRADE": 0, "XQ_DEGRADED_RULES_STRICT": 1,
         "XQ_TZ_EET_US": 0, "XQ_TZ_EET_EU": 1, "XQ_TZ_FIXED": 2, "XQ_LOG_DEBUG": 0, "XQ_LOG_INFO": 1,
         "XQ_LOG_WARN": 2, "XQ_LOG_ERROR": 3}

PRESETS = {
    "XauQuantumAI_backtest.set": {"InpMode": "XQ_MODE_BACKTEST", "InpShowDashboard": "false"},
    "XauQuantumAI_demo.set": {"InpMode": "XQ_MODE_DEMO"},
    "XauQuantumAI_demo_ai_native.set": {"InpMode": "XQ_MODE_DEMO", "InpAIMode": "XQ_AI_NATIVE"},
    "XauQuantumAI_demo_2pct_scaled.set": {"InpMode": "XQ_MODE_DEMO", "InpRiskPercent": "2.0",
                                          "InpMaxRiskPercentHard": "2.0", "InpMaxTotalRiskPercent": "2.0",
                                          "InpDailyLossLimitPercent": "4.0", "InpMaxDrawdownPercent": "12.0",
                                          "InpUseScaledEntries": "true"},
    "XauQuantumAI_live_conservative.set": {"InpMode": "XQ_MODE_LIVE", "InpRiskPercent": "0.25",
                                           "InpMaxRiskPercentHard": "0.5", "InpMaxTradesPerDay": "3",
                                           "InpMaxPositions": "1", "InpLiveConfirmation": "",
                                           "InpLiveAccount": "0"},
}


def parse_inputs():
    out = []
    for line in SRC.read_text().splitlines():
        m = re.match(r"\s*input\s+(\w+)\s+(Inp\w+)\s*=\s*(.+?);", line)
        if m:
            _, name, val = m.groups()
            out.append((name, val.strip().strip('"').replace("\\\\", "\\")))
    return out


def main():
    inputs = parse_inputs()
    for fname, over in PRESETS.items():
        lines = [f"; {fname} - generated by tools/make_set_files.py from XauQuantumAI.mq5"]
        for name, val in inputs:
            v = over.get(name, val)
            lines.append(f"{name}={ENUMS.get(v, v)}")
        (ROOT / "configs" / fname).write_text("\r\n".join(lines) + "\r\n")
        print(f"written configs/{fname} ({len(inputs)} inputs)")


if __name__ == "__main__":
    main()
